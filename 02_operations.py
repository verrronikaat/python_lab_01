# Расставьте знаки операций "плюс", "минус", "умножение" и скобки
# между числами "1 2 3 4 5" так, чтобы получилось число "25".


def get_expression_result():
    """Возвращает 25, расставив операции между 1 2 3 4 5."""
    return 1 * (2 + 3) * 4 + 5


if __name__ == '__main__':
    print(get_expression_result())